// Generates cross-language contract vectors from the JS reference engine.
// Usage: node tools/gen_vectors.mjs  → engine/tests/vectors/rng_gacha_vectors.json
// The C# port (core/) and any server implementation must reproduce these exactly.
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const require = createRequire(import.meta.url);
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const MF = require(join(root, 'engine', 'rules-core.js'));
const DATA = JSON.parse(readFileSync(join(root, 'data', 'game_data.json'), 'utf8'));
const out = { note: 'Generated by tools/gen_vectors.mjs from engine/rules-core.js. Do not edit by hand.', rng: [], below: [], gacha: [], stats: [], stageScale: [] };
for (const seed of [0, 1, 7, 20261014, 4294967295]) { const s = MF.Rng.seed(seed); out.rng.push({ seed, state: [...s], next: Array.from({ length: 12 }, () => MF.Rng.next(s)) }); }
for (const [seed, n] of [[1, 7], [99, 100], [20261014, 10000], [5, 3]]) { const s = MF.Rng.seed(seed); out.below.push({ seed, n, values: Array.from({ length: 20 }, () => MF.Rng.below(s, n)) }); }
for (const [banner, seed] of [['limited_lumi', 11], ['limited_kaya', 12], ['weapon_lumi', 13], ['weapon_kaya', 14], ['standard', 15]]) {
  const g = MF.Gacha.newState(seed); g.crystals = 1e9;
  const rs = []; for (let i = 0; i < 30; i++) rs.push(...MF.Gacha.pull(DATA, g, banner, 10));
  out.gacha.push({ banner, seed, results: rs.map((r) => `${r.rarity}:${r.id}`), endPity: g.pity });
}
out.curveMeans = Object.fromEntries(Object.entries(DATA.gacha.curves).map(([k, c]) => [k, MF.Gacha.stats(c, c.featuredSsrBps).mean]));
const ix = MF.indexData(DATA);
for (const e of [{ charId: 'sera', level: 1, weaponId: 'w_basic_ranged', weaponLevel: 1 }, { charId: 'sera', level: 37, weaponId: 'w_star_bow', weaponLevel: 33, armor: 4, accessory: 9, skillLv: 6 },
  { charId: 'harin', level: 60, weaponId: 'w_guard_saber', weaponLevel: 60, armor: 15, accessory: 15, skillLv: 10, ultLv: 10 }, { charId: 'lumi' }]) out.stats.push({ entry: e, derived: MF.Stats.derive(ix, e) });
for (let L = 1; L <= 60; L++) out.stageScale.push({ level: L, ...MF.Stats.stageScale(ix, L), xpToNext: L < 60 ? MF.Stats.xpToNext(ix, L) : 0 });
mkdirSync(join(root, 'engine', 'tests', 'vectors'), { recursive: true });
writeFileSync(join(root, 'engine', 'tests', 'vectors', 'rng_gacha_vectors.json'), JSON.stringify(out, null, 1));
console.log(`vectors: rng ${out.rng.length}, below ${out.below.length}, gacha ${out.gacha.length}×300, stats ${out.stats.length}, stage ${out.stageScale.length}`);
